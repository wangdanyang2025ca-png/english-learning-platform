function generateWords() {
  const cet4List = commonWords.split(/\s+/).filter(w => w.length > 0);
  const cet6List = cet6Words.split(/\s+/).filter(w => w.length > 0);

  const mockPronunciations = {
    'a': '/ə/', 'the': '/ðə/', 'is': '/ɪz/', 'to': '/tə/',
    'and': '/ænd/', 'of': '/əv/', 'in': '/ɪn/', 'that': '/ðæt/'
  };

  const words = [
    ...cet4List.map(w => ({
      word: w,
      ipa: mockPronunciations[w] || `/${w.charAt(0)}/`,
      definition_cn: `${w}的定义`,
      pos: 'n',
      categories: ['CET4'],
      examples: [`This is a ${w}.`]
    })),
    ...cet6List.map(w => ({
      word: w,
      ipa: mockPronunciations[w] || `/${w.charAt(0)}/`,
      definition_cn: `${w}的定义`,
      pos: 'v',
      categories: ['CET6'],
      examples: [`To ${w} is important.`]
    }))
  ];

  console.log(`✅ 生成了 ${words.length} 个单词`);
  console.log(`   - CET4: ${cet4List.length} 个`);
  console.log(`   - CET6: ${cet6List.length} 个`);
}

generateWords();
